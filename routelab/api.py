@router.get("/runs/{identity}/events")
async def events(identity: str):
    await asyncio.to_thread(require_job, identity)

    async def stream():
        previous = None
        while True:
            job = await asyncio.to_thread(require_job, identity)
            value = json.dumps(
                {
                    "id": identity,
                    "status": job["status"],
                    "progress": job["progress"],
                    "error": job["error"],
                },
                separators=(",", ":"),
            )
            if value != previous:
                yield f"event: progress\ndata: {value}\n\n"
                previous = value
            else:
                yield ": heartbeat\n\n"
            if job["status"] not in ("queued", "running"):
                yield "event: finished\ndata: {}\n\n"
                return
            await asyncio.sleep(0.75)

    return StreamingResponse(
        stream(),
        media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
    )


@router.get("/runs/{identity}/export")
def export(identity: str, format: Literal["json", "csv"] = "json"):
    job = require_job(identity)
    if format == "csv":
        result = job.get("result") or {}
        trials = result.get("trials", [result] if result else [])
        output = io.StringIO(newline="")
        writer = csv.writer(output)
        writer.writerow(
            [
                "algorithm",
                "seed",
                "status",
                "feasible",
                "vehicles",
                "distance_km",
                "solver_ms",
                "termination",
                "scenario_hash",
                "matrix_hash",
            ]
        )
        for trial in trials:
            ev = trial.get("evaluation", {})
            writer.writerow(
                [
                    trial.get("algorithm"),
                    trial.get("options", {}).get("seed"),
                    trial.get("status"),
                    ev.get("feasible"),
                    ev.get("vehicles_used"),
                    ev.get("distance_km"),
                    trial.get("solver_time_ms"),
                    trial.get("termination_reason"),
                    trial.get("scenario_hash"),
                    trial.get("matrix_hash"),
                ]
            )
        return Response(
            output.getvalue(),
            media_type="text/csv",
            headers={"Content-Disposition": f'attachment; filename="routelab-{identity[:8]}.csv"'},
        )
    return Response(
        json.dumps(job, indent=2, allow_nan=False),
        media_type="application/json",
        headers={"Content-Disposition": f'attachment; filename="routelab-{identity[:8]}.json"'},
    )


class EvaluateRequest(Model):
    scenario: Scenario
    routes: list[list[str]] = Field(max_length=25)


@router.post("/evaluate")
def evaluate_routes(request: EvaluateRequest):
    require_ready(request.scenario)
    if sum(map(len, request.routes)) > 200:
        raise HTTPException(422, "Candidate solution is too large")
    matrix = build_matrix(request.scenario)
    return {
        "evaluation": evaluate(request.scenario, matrix, request.routes),
        "scenario_hash": digest(request.scenario.model_dump()),
        "matrix_hash": matrix.hash,
    }
