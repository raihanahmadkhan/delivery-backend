def ortools_installed():
    return importlib.util.find_spec("ortools") is not None


def require_ready(scenario):
    try:
        road.assert_ready(scenario)
    except ValueError as exc:
        raise HTTPException(422, str(exc)) from exc


def require_solvable(scenario, algorithms, static_message):
    require_ready(scenario)
    if scenario.execution:
        raise HTTPException(422, static_message)
    if "exact" in algorithms and len(scenario.nodes) > 9:
        raise HTTPException(422, "Exact reference supports at most 8 customers")
    if "ortools" in algorithms and not ortools_installed():
        raise HTTPException(422, "Optional OR-Tools dependency is not installed")


def require_job(identity):
    job = store.get_job(identity)
    if job is None:
        raise HTTPException(404, "Run not found")
    return job


def submit(kind, body, key):
    if key and len(key) > 120:
        raise HTTPException(422, "Idempotency key is too long")
    try:
        identity = store.enqueue(kind, body, key)
    except OverflowError as exc:
        raise HTTPException(429, str(exc)) from exc
    except ValueError as exc:
        raise HTTPException(409, str(exc)) from exc
    return {"id": identity, "status": store.get_job(identity)["status"]}


