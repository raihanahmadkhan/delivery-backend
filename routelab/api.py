@router.post("/import")
async def upload(file: UploadFile = File(...)):
    content = bytearray()
    while chunk := await file.read(65536):
        content.extend(chunk)
        if len(content) > 2 * 1024 * 1024:
            raise HTTPException(413, "Scenario files may be at most 2 MB")
    try:
        scenario = await asyncio.to_thread(
            import_file, file.filename or "scenario.json", bytes(content)
        )
        if scenario.execution:
            raise ValueError("Import a static scenario without execution state")
        return scenario
    except (ValueError, TypeError, KeyError, csv.Error) as exc:
        raise HTTPException(422, str(exc)[:1000]) from exc


@router.post("/runs", status_code=202)
def run(request: RunRequest, idempotency_key: str | None = Header(default=None)):
    require_solvable(
        request.scenario, [request.options.algorithm], "Use /replans for execution-state problems"
    )
    store.save_scenario(request.scenario.model_dump())
    return submit("run", request.model_dump(), idempotency_key)


@router.post("/experiments", status_code=202)
def experiment(request: ExperimentRequest, idempotency_key: str | None = Header(default=None)):
    require_solvable(request.scenario, request.algorithms, "Experiments require static scenarios")
    store.save_scenario(request.scenario.model_dump())
    return submit("experiment", request.model_dump(), idempotency_key)


@router.post("/replans", status_code=202)
def replan(request: ReplanRequest, idempotency_key: str | None = Header(default=None)):
    parent = require_job(request.parent_job_id)
    if parent["status"] != "completed" or not (parent.get("result") or {}).get(
        "evaluation", {}
    ).get("feasible"):
        raise HTTPException(422, "Choose a completed feasible single run")
    if parent["kind"] != "run":
        raise HTTPException(422, "Replanning starts from a static single run")
    routes = parent["result"]["routes"]
    if request.vehicle_index >= len(routes) or request.completed_stops > len(
        routes[request.vehicle_index]
    ):
        raise HTTPException(
            422, "Choose a used vehicle and a completed-stop count within its route"
        )
    return submit("replan", request.model_dump(), idempotency_key)


